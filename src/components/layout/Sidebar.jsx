export default function Sidebar({ isOpen, onClose }) {
  const { subscription } = useAuth()

  const getTrialDays = () => {
    if (!subscription?.trial_ends_at) return 0
    const trialEnd = new Date(subscription.trial_ends_at)
    const now = new Date()
    const diff = Math.ceil((trialEnd - now) / (1000 * 60 * 60 * 24))
    return Math.max(0, diff)
  }

  const trialDays = getTrialDays()

  return (
    <>
      {/* Overlay for mobile */}
      {isOpen && (
        <div
          className="fixed inset-0 bg-black/50 z-40 lg:hidden"
          onClick={onClose}
        />
      )}

      {/* Sidebar */}
      <aside
        className={`
          fixed top-0 left-0 z-50 h-full w-64
          bg-surface border-r border-border
          transform transition-transform duration-[var(--transition-normal)]
          lg:translate-x-0 lg:static lg:z-auto
          ${isOpen ? 'translate-x-0' : '-translate-x-full'}
        `}
      >
        <div className="flex flex-col h-full">
          {/* Logo */}
          <div className="p-6 border-b border-border">
            <Logo size="md" />
          </div>

          {/* Navigation */}
          <nav className="flex-1 p-4 space-y-1 overflow-y-auto">
            {menuItems.map((item) => (
              <NavLink
                key={item.path}
                to={item.path}
                onClick={onClose}
                className={({ isActive }) => `
                  flex items-center gap-3 px-4 py-3
                  rounded-[var(--radius-md)]
                  text-sm font-medium
                  transition-all duration-[var(--transition-fast)]
                  ${isActive
                    ? 'bg-primary text-text-inverse'
                    : 'text-text-secondary hover:bg-surface-hover hover:text-text-primary'
                  }
                `}
              >
                {item.icon}
                <span>{item.label}</span>
              </NavLink>
            ))}
          </nav>

          {/* Plan info */}
          <div className="p-4 border-t border-border">
            <div className="p-4 bg-accent/10 rounded-[var(--radius-md)]">
              <div className="flex items-center gap-2 mb-1">
                <svg className="w-4 h-4 text-accent" fill="currentColor" viewBox="0 0 20 20">
                  <path fillRule="evenodd" d="M5 2a2 2 0 00-2 2v14l3.5-2 3.5 2 3.5-2 3.5 2V4a2 2 0 00-2-2H5zm2.5 3a1.5 1.5 0 100 3 1.5 1.5 0 000-3zm6.207.293a1 1 0 00-1.414 0l-6 6a1 1 0 101.414 1.414l6-6a1 1 0 000-1.414zM12.5 10a1.5 1.5 0 100 3 1.5 1.5 0 000-3z" clipRule="evenodd" />
                </svg>
                <span className="text-sm font-medium text-text-primary">Trial</span>
              </div>
              <p className="text-xs text-text-secondary">
                {trialDays > 0 ? (
                  <>
                    <span className="text-accent font-medium">{trialDays}</span> {trialDays === 1 ? 'dia restante' : 'dias restantes'}
                  </>
                ) : (
                  'Período expirado'
                )}
              </p>
            </div>
          </div>
        </div>
      </aside>
    </>
  )
}
